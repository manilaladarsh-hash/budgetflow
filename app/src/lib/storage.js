export const loadState = (now = new Date()) => {
  const raw = {
    categories: readJson(KEYS.categories, null),
    transactions: readJson(KEYS.transactions, []),
    weeksTracked: readNumber(KEYS.weeksTracked, 1),
    cycleStartDate: readString(KEYS.cycleStartDate, '') || null,
    cycleHistory: readJson(KEYS.cycleHistory, []),
    goals: readJson(KEYS.goals, []),
    subscriptions: readJson(KEYS.subscriptions, []),
    bills: readJson(KEYS.bills, []),
    netWorth: readJson(KEYS.netWorth, []),
    wishlist: readJson(KEYS.wishlist, []),
    tags: readJson(KEYS.tags, null) ?? [...DEFAULT_TAGS],
    streak: { count: readNumber(KEYS.streak, 0), lastDate: readString(KEYS.streakDate, '') || null },
    achievements: readJson(KEYS.achievements, []),
    importRules: readJson(KEYS.importRules, []),
    importProfiles: readJson(KEYS.importProfiles, {}),
    prefs: {
      onboarded: !!readString(KEYS.onboarded, ''),
      name: readString(KEYS.name, ''),
      currency: readString(KEYS.currency, '$') || '$',
      theme: readString(KEYS.theme, 'system'),
      dailyLimit: readNumber(KEYS.dailyLimit, 0),
      alertThreshold: readNumber(KEYS.alertThreshold, 0),
      geminiKey: readString(KEYS.geminiKey, ''),
      aiModel: readString(KEYS.aiModel, ''),
      cloudSync: readString(KEYS.cloudSync, 'on') !== 'off'
    }
  };
  // A brand-new install should start a fresh cycle "now", like the legacy app.
  if (!raw.cycleStartDate && !raw.categories) raw.cycleStartDate = now.toISOString();
  return normalizeState(raw, now);
};

