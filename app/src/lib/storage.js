const memoryStore = new Map();
const ls = () => {
  try {
    const s = globalThis.localStorage;
    if (s) return s;
  } catch { /* blocked storage */ }
  return {
    getItem: (k) => (memoryStore.has(k) ? memoryStore.get(k) : null),
    setItem: (k, v) => memoryStore.set(k, String(v)),
    removeItem: (k) => memoryStore.delete(k),
    clear: () => memoryStore.clear(),
    key: (i) => [...memoryStore.keys()][i] ?? null,
    get length() { return memoryStore.size; }
  };
};

const readJson = (key, fallback) => {
  try {
    const raw = ls().getItem(key);
    if (raw === null || raw === undefined || raw === '') return fallback;
    const v = JSON.parse(raw);
    return v ?? fallback;
  } catch {
    return fallback;
  }
};
const readNumber = (key, fallback) => {
  const n = parseFloat(ls().getItem(key));
  return Number.isFinite(n) ? n : fallback;
};
const readString = (key, fallback = '') => {
  const v = ls().getItem(key);
  return v === null || v === undefined ? fallback : v;
};

const num = (v, fallback = 0) => {
  const n = typeof v === 'number' ? v : parseFloat(v);
  return Number.isFinite(n) ? n : fallback;
};

// ---- Normalisation / migration (pure) ----

export const normalizeCategories = (cats) => {
  if (!Array.isArray(cats)) return null;
  const list = cats.filter((c) => c && c.id !== undefined && c.id !== null).map((c) => ({
    ...c,
    id: String(c.id),
    name: String(c.name ?? 'Untitled'),
    limit: num(c.limit),
    balance: num(c.balance),
    icon: c.icon || 'circle',
    frequency: c.frequency === 'monthly' ? 'monthly' : 'weekly',
    pinned: !!c.pinned
  }));
  const needsOrder = list.some((c) => typeof c.order !== 'number');
  if (needsOrder) {
    // Legacy order: by id (string compare), as the old app displayed them.
    [...list].sort((a, b) => a.id.localeCompare(b.id)).forEach((c, i) => {
      if (typeof c.order !== 'number') c.order = i;
    });
  }
  return list;
};

export const sortCategories = (cats) =>
  [...cats].sort((a, b) => (b.pinned - a.pinned) || (a.order ?? 0) - (b.order ?? 0) || a.id.localeCompare(b.id));

export const normalizeTransactions = (txs) => {
  if (!Array.isArray(txs)) return [];
  return txs.filter((t) => t && t.id !== undefined && t.id !== null).map((t) => {
    const tx = { ...t, id: String(t.id), amount: num(t.amount) };
    if (!Array.isArray(tx.tags)) tx.tags = tx.tags ? [String(tx.tags)] : [];
    // Legacy bug: copies generated by the cycle kept their recurring flag and
    // multiplied every week. Copies are recognisable by the 🔁 prefix.
    if (tx.recurring && tx.recurring !== 'none' && !tx.recurringSourceId && typeof tx.description === 'string' && tx.description.startsWith('🔁')) {
      tx.recurring = 'none';
      tx.recurringSourceId = 'legacy';
    }
    return tx;
  }).sort((a, b) => new Date(b.date) - new Date(a.date));
};

const list = (v) => (Array.isArray(v) ? v : []);

// Produces a clean app state from any partial/legacy shape.
export const normalizeState = (raw, now = new Date()) => {
  const categories = normalizeCategories(raw.categories) ?? INITIAL_CATEGORIES.map((c) => ({ ...c }));
  const start = raw.cycleStartDate ? new Date(raw.cycleStartDate) : null;
  return {
    categories,
    transactions: normalizeTransactions(raw.transactions),
    weeksTracked: Math.max(1, Math.round(num(raw.weeksTracked, 1))),
    cycleStartDate: start && !Number.isNaN(start.getTime()) ? start.toISOString() : startOfWeekSunday(now).toISOString(),
    cycleHistory: list(raw.cycleHistory),
    goals: list(raw.goals).map((g) => ({ ...g, target: num(g.target), saved: num(g.saved), deposits: list(g.deposits) })),
    subscriptions: list(raw.subscriptions).map((s) => ({ ...s, amount: num(s.amount), active: s.active !== false })),
    bills: list(raw.bills).map((b) => ({ ...b, amount: num(b.amount), dueDay: Math.min(31, Math.max(1, Math.round(num(b.dueDay, 1)))) })),
    netWorth: list(raw.netWorth).map((i) => ({ ...i, amount: num(i.amount), type: i.type === 'liability' ? 'liability' : 'asset' })),
    wishlist: list(raw.wishlist).map((w) => ({ ...w, price: num(w.price) })),
    tags: Array.isArray(raw.tags) ? raw.tags.filter((t) => typeof t === 'string') : [...DEFAULT_TAGS],
    streak: { count: Math.max(0, Math.round(num(raw.streak?.count))), lastDate: raw.streak?.lastDate || null },
    achievements: list(raw.achievements),
    importRules: list(raw.importRules).filter((r) => r && r.match),
    importProfiles: raw.importProfiles && typeof raw.importProfiles === 'object' && !Array.isArray(raw.importProfiles) ? raw.importProfiles : {},
    prefs: {
      onboarded: !!raw.prefs?.onboarded,
      name: raw.prefs?.name || '',
      currency: raw.prefs?.currency && String(raw.prefs.currency).length <= 4 ? raw.prefs.currency : '$',
      theme: ['light', 'dark', 'system'].includes(raw.prefs?.theme) ? raw.prefs.theme : 'system',
      dailyLimit: Math.max(0, num(raw.prefs?.dailyLimit)),
      alertThreshold: Math.max(0, num(raw.prefs?.alertThreshold)),
      geminiKey: raw.prefs?.geminiKey || '',
      aiModel: GEMINI_MODELS.some((m) => m.id === raw.prefs?.aiModel) ? raw.prefs.aiModel : GEMINI_MODELS[0].id,
      cloudSync: raw.prefs?.cloudSync !== false
    }
  };
};

